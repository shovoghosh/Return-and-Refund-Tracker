// Cloudflare Worker entry point.
//
// OpenNext generates `.open-next/worker.js`, which exports only a fetch handler.
// Wrapping it lets us add a Cron Trigger handler in the same Worker, so the
// reminder sweep needs no second deployment or external scheduler.
//
// The scheduled sweep calls the app's own `/api/cron/reminders` endpoint rather
// than importing the reminder service directly: the endpoint already owns the
// secret check, the idempotent dispatch logic, and its JSON summary, and it
// keeps Prisma's bundling concerns inside the generated Worker.
//
// This module is generated by `opennextjs-cloudflare build`, so it does not
// exist when TypeScript runs on a clean checkout. `@ts-ignore` (not
// `@ts-expect-error`) is deliberate: after a build the file resolves, and an
// expect-error would then fail the type check.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore
import { default as handler } from "./.open-next/worker.js";

interface WorkerEnv {
  APP_URL?: string;
  CRON_SECRET?: string;
}

interface ScheduledControllerLike {
  scheduledTime: number;
  cron: string;
}

interface ExecutionContextLike {
  waitUntil(promise: Promise<unknown>): void;
}

const worker = {
  fetch: handler.fetch,

  async scheduled(
    _controller: ScheduledControllerLike,
    env: WorkerEnv,
    ctx: ExecutionContextLike,
  ): Promise<void> {
    const base = env.APP_URL?.trim();
    if (!base) {
      console.error("[cron] APP_URL is not set; cannot dispatch reminders.");
      return;
    }

    const url = new URL("/api/cron/reminders", base);
    const run = fetch(url, {
      method: "POST",
      headers: env.CRON_SECRET ? { authorization: `Bearer ${env.CRON_SECRET}` } : {},
    })
      .then(async (response) => {
        const body = await response.text();
        if (!response.ok) {
          console.error(`[cron] reminder dispatch failed (${response.status}): ${body}`);
          return;
        }
        console.log(`[cron] reminder dispatch ok: ${body}`);
      })
      .catch((error: unknown) => {
        console.error("[cron] reminder dispatch threw", error);
      });

    ctx.waitUntil(run);
  },
};

export default worker;
